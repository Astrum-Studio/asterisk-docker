#!/usr/bin/env bash
# Generate autodistribution dialplan with secrets from env (never commit real keys).
set -euo pipefail

OUT="/data/astrum/astrum-forward.conf"
KEY="${ASTRUM_PORTAL_API_KEY:-}"
URL="${ASTRUM_PORTAL_FORWARD_URL:-}"

mkdir -p /data/astrum

if [ -z "${KEY}" ] || [ -z "${URL}" ]; then
  cat >"${OUT}" <<'EOF'
; Autodistribution disabled — set ASTRUM_PORTAL_API_KEY and ASTRUM_PORTAL_FORWARD_URL in .env
[from-astrum-forward]
exten => _X.,1,NoOp(Asterisk24 forward disabled — missing portal env)
 same => n,Goto(from-internal,s,1)
EOF
  echo "[ensure-astrum-dialplan] forward dialplan disabled (missing ASTRUM_PORTAL_* env)" >&2
  exit 0
fi

# Strip CR/LF from secrets before writing dialplan.
KEY="${KEY//$'\r'/}"
KEY="${KEY//$'\n'/}"
URL="${URL//$'\r'/}"
URL="${URL//$'\n'/}"

cat >"${OUT}" <<EOF
; Generated by ensure-astrum-dialplan.sh — do not edit manually
[from-astrum-forward]
exten => _X.,1,NoOp(Asterisk24 forward for \${EXTEN})
 same => n,Set(CURLOPT(hashcompat)=yes)
 same => n,Set(CURLOPT(httptimeout)=20)
 same => n,Set(CURLOPT(conntimeout)=20)
 same => n,Set(CURLOPT(httpheader)=X-Portal-Api-Key: ${KEY})
 same => n,Set(HASH(forwardHash)=\${CURL(${URL}?phone=\${CALLERID(num)}&trunk=\${EXTEN})})
 same => n,GotoIf(\$["\${HASH(forwardHash,name)}" != ""]?setname:route)
 same => n(setname),Set(CALLERID(name)=\${HASH(forwardHash,name)})
 same => n(route),GotoIf(\$["\${HASH(forwardHash,number)}" != ""]?from-internal,\${HASH(forwardHash,number)},1:fallback)
 same => n(fallback),Goto(from-internal,s,1)
EOF

echo "[ensure-astrum-dialplan] wrote ${OUT}"
